#ifndef ARINO_OPCODES_H
#define ARINO_OPCODES_H

/* One-byte micro-opcodes consumed by the DFA engine. */
enum ArinoOpcode {
    ARINO_OP_ADVANCE_CURSOR = 0b00000001,
    ARINO_OP_SET_SPAN_START = 0b00000010,
    ARINO_OP_EMIT_TOKEN = 0b00000100,
    ARINO_OP_DISCARD_BYTE = 0b00001000,
    ARINO_OP_REPORT_ERROR = 0b00010000,
    ARINO_OP_RECORD_DECIMAL = 0b00100000,
    ARINO_OP_EMIT_SYMBOL = 0b01000000
};

#endif
